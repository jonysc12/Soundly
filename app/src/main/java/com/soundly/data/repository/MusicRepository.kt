        if (inMemory.isNotEmpty()) return@withContext inMemory
        mediaStore.getSongs()
    }

    suspend fun ensureLibrarySongsLoaded() = withContext(Dispatchers.IO) {
        bootstrapFromLocalCache()
        if (!mediaStoreSyncDone) {
            refreshLibrarySongs(force = true)
        }
    }

    suspend fun refreshLibrarySongs() = withContext(Dispatchers.IO) {
        refreshLibrarySongs(force = true)
    }

    private suspend fun refreshLibrarySongs(force: Boolean) {
        refreshMutex.withLock {
            if (!force && !mediaStoreSyncDone) return@withLock

            if (!hasAudioReadPermission()) {
                clearLocalCache()
                mediaStoreSyncDone = true
                return@withLock
            }

            val settings = MediaScannerPreferences.getSettings(context)
            val allSongs = mediaStore.getSongs()
            val filteredSongs = filterSongs(
                songs = allSongs,
                ignoreTempFolders = settings.ignoreTempFolders,
                ignoreShortAudios = settings.ignoreShortAudios,
                manuallyBlockedFolders = settings.blockedFolders,
                manuallyBlockedSongIds = settings.blockedSongIds
            )

            lastScannedSourceSongs.value = allSongs
            syncSongsIncrementally(filteredSongs)
            mediaStoreSyncDone = true
        }
    }

    private suspend fun syncSongsIncrementally(newSongs: List<Song>) {
        val incomingEntities = newSongs.map { it.toEntity() }
        val incomingIds = incomingEntities.mapTo(mutableSetOf()) { it.id }

        val currentEntities = songCacheDao.getSongs()
        val currentById = currentEntities.associateBy { it.id }

        val toUpsert = incomingEntities.filter { incoming ->
            currentById[incoming.id] != incoming
        }
        val toDeleteIds = currentById.keys.filterNot { incomingIds.contains(it) }

        database.withTransaction {
            if (toUpsert.isNotEmpty()) {
                songCacheDao.upsertSongs(toUpsert)
            }
            if (toDeleteIds.isNotEmpty()) {
                songCacheDao.deleteSongsByIds(toDeleteIds)
            }
        }

        librarySongs.value = sortSongs(newSongs)
    }

    private suspend fun clearLocalCache() {
        database.withTransaction {
            songCacheDao.clearAllSongs()
        }
        librarySongs.value = emptyList()
        lastScannedSourceSongs.value = emptyList()
    }

    private fun observeLocalCache() {
        repositoryScope.launch {
            songCacheDao.observeSongs().collectLatest { entities ->
                librarySongs.value = entities.map { it.toDomain() }
                cacheBootstrapDone = true
            }
        }
    }

    private fun observeLibraryMetadata() {
        repositoryScope.launch {
            libraryMetadataDao.observeFavoriteSongIds().collectLatest { ids ->
                favoriteSongIds.value = ids.toSet()
            }
        }
        repositoryScope.launch {
            libraryMetadataDao.observeFavoriteAlbumIds().collectLatest { ids ->
                favoriteAlbumIds.value = ids.toSet()
            }
        }
        repositoryScope.launch {
            libraryMetadataDao.observeFavoriteArtistIds().collectLatest { ids ->
                favoriteArtistIds.value = ids.toSet()
            }
        }
        repositoryScope.launch {
            libraryMetadataDao.observePlaylists().collectLatest { entities ->
                playlistEntities.value = entities
            }
        }
        repositoryScope.launch {
            libraryMetadataDao.observePlaylistSongs().collectLatest { entities ->
                playlistSongEntities.value = entities
            }
        }
        repositoryScope.launch {
            combine(playlistEntities, playlistSongEntities, favoriteSongIds, librarySongs) { entities, playlistSongs, favoriteSongs, songs ->
                val visibleLikedSongs = songs.count { it.id in favoriteSongs }
                val visibleSongIds = songs.mapTo(mutableSetOf(), Song::id)
                val playlistSongCounts = playlistSongs
                    .groupBy { it.playlistId }
                    .mapValues { (_, entries) ->
                        entries.count { entry -> entry.songId in visibleSongIds }
                    }

                entities.map { entity ->
                    entity.toDomain(
                        likedSongCount = visibleLikedSongs,
                        playlistSongCount = playlistSongCounts[entity.id] ?: 0
                    )
                }
            }.collectLatest { currentPlaylists ->
                playlists.value = currentPlaylists
            }
        }
    }

    private suspend fun bootstrapFromLocalCache() {
        if (cacheBootstrapDone) return
        val cached = songCacheDao.getSongs().map { it.toDomain() }
        librarySongs.value = cached
        cacheBootstrapDone = true
    }

    private suspend fun ensureLikedSongsPlaylist(now: Long) {
        if (libraryMetadataDao.getPlaylistById(LIKED_SONGS_PLAYLIST_ID) != null) return
        libraryMetadataDao.upsertPlaylist(
            PlaylistEntity(
                id = LIKED_SONGS_PLAYLIST_ID,
                name = LIKED_SONGS_PLAYLIST_NAME,
                type = LIKED_SONGS_PLAYLIST_TYPE,
                artworkUri = null,
                createdAt = now,
                updatedAt = now
            )
        )
    }

    private fun persistPlaylistArtwork(
        playlistId: String,
        sourceUri: Uri
    ): String? {
        return runCatching {
            val artworkDirectory = File(context.filesDir, PLAYLIST_ARTWORK_DIRECTORY).apply {
                mkdirs()
            }
            val artworkFile = File(artworkDirectory, "$playlistId.jpg")
            context.contentResolver.openInputStream(sourceUri)?.use { input ->
                artworkFile.outputStream().use { output -> input.copyTo(output) }
            } ?: return null
            Uri.fromFile(artworkFile).toString()
        }.getOrNull()
    }

    private fun registerMediaStoreObserver() {
        if (mediaStoreObserver != null) return

        val observer = object : ContentObserver(Handler(Looper.getMainLooper())) {
            override fun onChange(selfChange: Boolean) {
                scheduleStorageRefresh()
            }

            override fun onChange(selfChange: Boolean, uri: Uri?) {
                scheduleStorageRefresh()
            }
        }

        context.contentResolver.registerContentObserver(
            MediaStore.Audio.Media.EXTERNAL_CONTENT_URI,
            true,
            observer
        )
        mediaStoreObserver = observer
    }

    private fun scheduleStorageRefresh() {
        pendingRefreshJob?.cancel()
        pendingRefreshJob = repositoryScope.launch {
            delay(MEDIASTORE_REFRESH_DEBOUNCE_MS)
            refreshLibrarySongs(force = true)
        }
    }

    private fun hasAudioReadPermission(): Boolean {
        val permission = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
            Manifest.permission.READ_MEDIA_AUDIO
        } else {
            Manifest.permission.READ_EXTERNAL_STORAGE
        }
        return ContextCompat.checkSelfPermission(context, permission) == PackageManager.PERMISSION_GRANTED
    }

    private fun filterSongs(
        songs: List<Song>,
        ignoreTempFolders: Boolean,
        ignoreShortAudios: Boolean,
        manuallyBlockedFolders: Set<String>,
        manuallyBlockedSongIds: Set<Long>
    ): List<Song> {
        return songs.filter { song ->
            val blockedTemp = ignoreTempFolders && song.path.isTempFolderPath()
            val blockedShort = ignoreShortAudios && song.duration < MIN_AUDIO_DURATION_MS
            val blockedManualFolder = manuallyBlockedFolders.contains(song.folderPath())
            val blockedManualSong = manuallyBlockedSongIds.contains(song.id)
            !(blockedTemp || blockedShort || blockedManualFolder || blockedManualSong)
        }
    }

    private fun sortSongs(songs: List<Song>): List<Song> {
        return songs.sortedWith(compareBy<Song> { it.title.lowercase() }.thenBy { it.id })
    }

    private fun String.isTempFolderPath(): Boolean {
        val normalized = lowercase()
        return TEMP_FOLDER_PATTERNS.any { normalized.contains(it) }
    }

    private fun Song.folderPath(): String {
        val normalized = path.replace('\\', '/')
        return normalized.substringBeforeLast('/', missingDelimiterValue = normalized)
    }

    companion object {
        const val LIKED_SONGS_PLAYLIST_ID = "liked_songs"
        const val LIKED_SONGS_PLAYLIST_TYPE = "auto_liked_songs"
        const val USER_PLAYLIST_TYPE = "user_created"
        private const val LIKED_SONGS_PLAYLIST_NAME = "Tus me gusta"
        private const val USER_PLAYLIST_ID_PREFIX = "playlist_"
        private const val PLAYLIST_ARTWORK_DIRECTORY = "playlist_artwork"
        private const val MIN_AUDIO_DURATION_MS = 60_000L
        private const val DISCOVERY_BATCH_SIZE = 12
        private const val MEDIASTORE_REFRESH_DEBOUNCE_MS = 650L
        private val TEMP_FOLDER_PATTERNS = listOf(
            "/whatsapp/",
            "/telegram/",
            "/cache/",
            "/temp/",
            "/tmp/"
        )
    }
}

private fun PlaylistEntity.toDomain(
    likedSongCount: Int,
    playlistSongCount: Int
): Playlist {
    return Playlist(
        id = id,
        name = name,
        songCount = if (type == MusicRepository.LIKED_SONGS_PLAYLIST_TYPE) likedSongCount else playlistSongCount,
        isAutoGenerated = type == MusicRepository.LIKED_SONGS_PLAYLIST_TYPE,
        artworkUri = artworkUri?.let { uriStr ->
            // Cache busting: append timestamp to ensure Coil reloads if file changed
            Uri.parse("$uriStr?t=$updatedAt")
        },
        updatedAt = updatedAt
    )
}
