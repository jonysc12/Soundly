    suspend fun scanSongs(
        ignoreTempFolders: Boolean,
        ignoreShortAudios: Boolean,
        manuallyBlockedFolders: Set<String> = emptySet(),
        manuallyBlockedSongIds: Set<Long> = emptySet(),
        onDiscoveredBatch: suspend (List<String>) -> Unit
    ): MusicScanReport = withContext(Dispatchers.IO) {
        val imported = mutableListOf<Song>()
        val scannedSource = mutableListOf<Song>()
        val discoveredBatch = mutableListOf<String>()
        var blockedByTemp = 0
        var blockedByShort = 0
        var scannedCount = 0

        mediaStore.streamSongs { song ->
            scannedCount++
            scannedSource.add(song)
            discoveredBatch.add(song.title.ifBlank { "(Sin nombre)" })

            val blockedTemp = ignoreTempFolders && song.path.isTempFolderPath()
            val blockedShort = ignoreShortAudios && song.duration < MIN_AUDIO_DURATION_MS
            val blockedManualFolder = manuallyBlockedFolders.contains(song.folderPath())
            val blockedManualSong = manuallyBlockedSongIds.contains(song.id)
            val blocked = blockedTemp || blockedShort || blockedManualFolder || blockedManualSong

            if (blockedTemp) blockedByTemp++
            if (blockedShort) blockedByShort++
            if (!blocked) imported.add(song)

            if (discoveredBatch.size >= DISCOVERY_BATCH_SIZE) {
                val batch = discoveredBatch.toList()
                discoveredBatch.clear()
                runBlocking { onDiscoveredBatch(batch) }
            }
        }

        if (discoveredBatch.isNotEmpty()) {
            onDiscoveredBatch(discoveredBatch.toList())
        }

        MediaScannerPreferences.saveSettings(
            context = context,
            settings = MediaScannerSettings(
                ignoreTempFolders = ignoreTempFolders,
                ignoreShortAudios = ignoreShortAudios,
                blockedFolders = manuallyBlockedFolders,
                blockedSongIds = manuallyBlockedSongIds
            )
        )

        lastScannedSourceSongs.value = scannedSource
        syncSongsIncrementally(imported)
        mediaStoreSyncDone = true

        val report = MusicScanReport(
            scannedSongs = scannedCount,
            importedSongs = imported.size,
            blockedSongs = scannedCount - imported.size,
            blockedByTempFolders = blockedByTemp,
            blockedByShortDuration = blockedByShort,
            activeFilters = MusicScanFilters(
                ignoreTempFolders = ignoreTempFolders,
                ignoreShortAudios = ignoreShortAudios
            )
        )
        _lastScanReport.value = report
        report
    }

