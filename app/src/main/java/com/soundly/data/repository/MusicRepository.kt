    }

    suspend fun createPlaylist(
        name: String,
        artworkSourceUri: Uri
    ): String = withContext(Dispatchers.IO) {
        val trimmedName = name.trim()
        require(trimmedName.isNotEmpty()) { "Playlist name cannot be blank." }

        val playlistId = USER_PLAYLIST_ID_PREFIX + UUID.randomUUID().toString()
        val now = System.currentTimeMillis()
        val persistedArtworkUri = persistPlaylistArtwork(
            playlistId = playlistId,
            sourceUri = artworkSourceUri
        ) ?: error("Unable to persist playlist artwork.")

        libraryMetadataDao.upsertPlaylist(
            PlaylistEntity(
                id = playlistId,
                name = trimmedName,
                type = USER_PLAYLIST_TYPE,
                artworkUri = persistedArtworkUri,
                createdAt = now,
                updatedAt = now
            )
        )
        playlistId
    }

    suspend fun deletePlaylist(playlistId: String) = withContext(Dispatchers.IO) {
        database.withTransaction {
            val playlist = libraryMetadataDao.getPlaylistById(playlistId)
            if (playlist?.type == USER_PLAYLIST_TYPE) {
                // Delete artwork file if it exists
                playlist.artworkUri?.let { uriStr ->
                    runCatching {
                        val uri = Uri.parse(uriStr)
                        if (uri.scheme == "file") {
                            File(uri.path ?: "").delete()
                        }
                    }
                }
                libraryMetadataDao.deletePlaylistSongs(playlistId)
                libraryMetadataDao.deletePlaylist(playlistId)
            }
        }
    }

    suspend fun updatePlaylist(
        id: String,
        name: String,
        artworkSourceUri: Uri?
    ) = withContext(Dispatchers.IO) {
        val playlist = libraryMetadataDao.getPlaylistById(id) ?: return@withContext
        if (playlist.type != USER_PLAYLIST_TYPE) return@withContext

        val trimmedName = name.trim()
        require(trimmedName.isNotEmpty()) { "Playlist name cannot be blank." }

        val now = System.currentTimeMillis()
        var newArtworkUri = playlist.artworkUri

        if (artworkSourceUri != null) {
            // Delete old artwork if it was a file
            playlist.artworkUri?.let { oldUriStr ->
                runCatching {
                    val oldUri = Uri.parse(oldUriStr)
                    if (oldUri.scheme == "file") {
                        File(oldUri.path ?: "").delete()
                    }
                }
            }
            newArtworkUri = persistPlaylistArtwork(id, artworkSourceUri)
        }

        libraryMetadataDao.updatePlaylist(
            playlistId = id,
            name = trimmedName,
            artworkUri = newArtworkUri,
            updatedAt = now
        )
    }

    suspend fun addSongToPlaylist(
        playlistId: String,
        songId: Long
    ): Boolean = withContext(Dispatchers.IO) {
        database.withTransaction {
            val playlist = libraryMetadataDao.getPlaylistById(playlistId) ?: return@withTransaction false
            if (playlist.type != USER_PLAYLIST_TYPE) return@withTransaction false
            if (libraryMetadataDao.playlistContainsSong(playlistId, songId)) return@withTransaction false

            val now = System.currentTimeMillis()
            libraryMetadataDao.upsertPlaylistSongs(
                listOf(
                    PlaylistSongEntity(
                        playlistId = playlistId,
                        songId = songId,
                        addedAt = now
                    )
                )
            )
            libraryMetadataDao.touchPlaylist(playlistId, now)
            true
        }
    }

    suspend fun removeSongFromPlaylist(
        playlistId: String,
        songId: Long
    ): Boolean = withContext(Dispatchers.IO) {
        database.withTransaction {
            val playlist = libraryMetadataDao.getPlaylistById(playlistId) ?: return@withTransaction false
            if (playlist.type != USER_PLAYLIST_TYPE && playlistId != LIKED_SONGS_PLAYLIST_ID) {
                return@withTransaction false
            }

            if (playlistId == LIKED_SONGS_PLAYLIST_ID) {
                if (!libraryMetadataDao.isSongFavorite(songId)) return@withTransaction false
                libraryMetadataDao.deleteFavoriteSong(songId)
            } else {
                if (!libraryMetadataDao.playlistContainsSong(playlistId, songId)) return@withTransaction false
                libraryMetadataDao.deletePlaylistSong(playlistId, songId)
            }

            libraryMetadataDao.touchPlaylist(playlistId, System.currentTimeMillis())
            true
        }
    }

    fun playlistIdsContainingSong(songId: Long): Flow<Set<String>> {
        return playlistSongEntities.asStateFlow().map { entries ->
            entries.asSequence()
                .filter { it.songId == songId }
                .map { it.playlistId }
                .toSet()
        }
    }

    suspend fun hideSong(songId: Long): Boolean = withContext(Dispatchers.IO) {
        val settings = MediaScannerPreferences.getSettings(context)
        if (songId in settings.blockedSongIds) return@withContext false

        database.withTransaction {
            if (libraryMetadataDao.isSongFavorite(songId)) {
                libraryMetadataDao.deleteFavoriteSong(songId)
            }
            libraryMetadataDao.deletePlaylistEntriesBySongId(songId)
        }

        MediaScannerPreferences.saveSettings(
            context = context,
            settings = settings.copy(
                blockedSongIds = settings.blockedSongIds + songId
            )
        )
        refreshLibrarySongs(force = true)
        true
    }

    fun getSongsForPlaylist(playlistId: String): Flow<List<Song>> {
        return combine(
            librarySongsFlow,
            favoriteSongIdsFlow,
            playlistSongEntities.asStateFlow()
        ) { songs, favoriteSongs, playlistEntries ->
            when (playlistId) {
                LIKED_SONGS_PLAYLIST_ID -> songs.filter { it.id in favoriteSongs }
                else -> {
                    val orderedSongIds = playlistEntries
                        .asSequence()
                        .filter { it.playlistId == playlistId }
                        .sortedByDescending { it.addedAt }
                        .map { it.songId }
                        .toList()

                    if (orderedSongIds.isEmpty()) {
                        emptyList()
                    } else {
                        val songsById = songs.associateBy { it.id }
                        orderedSongIds.mapNotNull(songsById::get)
                    }
                }
            }
        }
    }

