    suspend fun toggleSongFavorite(songId: Long): Boolean = withContext(Dispatchers.IO) {
        database.withTransaction {
            val isFavorite = libraryMetadataDao.isSongFavorite(songId)
            val now = System.currentTimeMillis()
            if (isFavorite) {
                libraryMetadataDao.deleteFavoriteSong(songId)
            } else {
                ensureLikedSongsPlaylist(now)
                libraryMetadataDao.upsertFavoriteSong(
                    FavoriteSongEntity(songId = songId, createdAt = now)
                )
            }
            libraryMetadataDao.touchPlaylist(LIKED_SONGS_PLAYLIST_ID, now)
            !isFavorite
        }
    }

    suspend fun toggleAlbumFavorite(albumId: Long): Boolean = withContext(Dispatchers.IO) {
        database.withTransaction {
            val isFavorite = libraryMetadataDao.isAlbumFavorite(albumId)
            if (isFavorite) {
                libraryMetadataDao.deleteFavoriteAlbum(albumId)
            } else {
                libraryMetadataDao.upsertFavoriteAlbum(
                    FavoriteAlbumEntity(
                        albumId = albumId,
                        createdAt = System.currentTimeMillis()
                    )
                )
            }
            !isFavorite
        }
    }

    suspend fun toggleArtistFavorite(artistId: Long): Boolean = withContext(Dispatchers.IO) {
        database.withTransaction {
            val isFavorite = libraryMetadataDao.isArtistFavorite(artistId)
            if (isFavorite) {
                libraryMetadataDao.deleteFavoriteArtist(artistId)
            } else {
                libraryMetadataDao.upsertFavoriteArtist(
                    FavoriteArtistEntity(
                        artistId = artistId,
                        createdAt = System.currentTimeMillis()
                    )
                )
            }
            !isFavorite
        }
    }

    // --- PLAY HISTORY ---
    suspend fun recordSongPlay(songId: Long) = withContext(Dispatchers.IO) {
        database.withTransaction {
            val history = libraryMetadataDao.getPlayHistory(songId)
            val now = System.currentTimeMillis()
            if (history == null) {
                libraryMetadataDao.upsertPlayHistory(
                    PlayHistoryEntity(songId = songId, lastPlayedAt = now, playCount = 1)
                )
            } else {
                libraryMetadataDao.upsertPlayHistory(
                    history.copy(lastPlayedAt = now, playCount = history.playCount + 1)
                )
            }
        }
    }

