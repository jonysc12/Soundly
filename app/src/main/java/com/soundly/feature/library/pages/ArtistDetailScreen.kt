@Composable
private fun ArtistTopBar(
    artistName      : String,
    topBarBackground: Color,
    backIconColor   : Color,
    collapseProgress: Float,
    onBack          : () -> Unit
) {
    val density    = LocalDensity.current
    val titleStyle = MaterialTheme.typography.titleLarge

    Box(
        modifier = Modifier
            .fillMaxWidth()
            .background(topBarBackground)
            .statusBarsPadding()
            .height(56.dp)
    ) {
        IconButton(
            onClick  = onBack,
            modifier = Modifier.align(Alignment.CenterStart).padding(start = 4.dp)
        ) {
            Icon(
                imageVector        = Icons.AutoMirrored.Filled.ArrowBack,
                contentDescription = "Volver",
                tint               = backIconColor
            )
        }

        val titleAlpha  = ((collapseProgress - 0.65f) / 0.35f).coerceIn(0f, 1f)
        val titleOffset = lerpDp(14.dp, 0.dp, collapseProgress)

        Box(
            modifier = Modifier
                .align(Alignment.Center)
                .fillMaxWidth()
                .padding(horizontal = 56.dp)
                .graphicsLayer {
                    alpha        = titleAlpha
                    translationY = with(density) { titleOffset.toPx() }
                }
        ) {
            Text(
                text       = artistName,
                style      = titleStyle,
                fontWeight = FontWeight.Bold,
                color      = MaterialTheme.colorScheme.onSurface,
                maxLines   = 1,
                overflow   = TextOverflow.Ellipsis
            )
        }
    }
}



