            modifier = Modifier
                .fillMaxWidth()
                .height(220.dp)
                .align(Alignment.BottomCenter)
                .background(
                    Brush.verticalGradient(
                        colors = listOf(Color.Transparent, gradientBottomColor)
                    )
                )
        )

        // 3. Nombre del artista
        Column(
            modifier = Modifier
                .align(Alignment.BottomStart)
                .fillMaxWidth()
                .padding(horizontal = 20.dp)
                .padding(bottom = 20.dp, top = 72.dp)
                .graphicsLayer {
                    translationY = -with(density) { 40.dp.toPx() } * collapseProgress
                    alpha        = (1f - collapseProgress / 0.65f).coerceIn(0f, 1f)
                }
        ) {
            Text(
                text       = artistName,
                style      = MaterialTheme.typography.displayLarge,
                fontWeight = FontWeight.Black,
                color      = artistNameColor,
                maxLines   = 2,
                overflow   = TextOverflow.Ellipsis,
                lineHeight = MaterialTheme.typography.displayLarge.fontSize * 0.95
            )
            Spacer(Modifier.height(6.dp))
            Text(
                text = pluralize(songCount, "canción", "canciones") + "  •  " +
                    pluralize(albumCount, "álbum", "álbumes"),
                style = MaterialTheme.typography.titleMedium,
                fontWeight = FontWeight.Medium,
                color = artistNameColor.copy(alpha = 0.88f)
            )
        }

        // 4. Triple ola inferior
        val canvasHeightDp = waveHeightDp * 2.5f
        Canvas(
            modifier = Modifier
                .fillMaxWidth()
                .height(canvasHeightDp)
                .align(Alignment.BottomCenter)
        ) {
            drawQuadWave(color = backgroundColor, waveHeight = waveHeightDp.toPx())
        }
    }
